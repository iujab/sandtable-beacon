#!/usr/bin/env python3
"""Rig layout for the exercise mode: where the anchors go and where to tape the floor plan.

Reads a kit scenario file (the anchors) and the twin, applies the default registration, and writes
  hardware/rig_layout.svg   the plan in rig coordinates with anchors, tape lines and marks (vector: print at any size)
  hardware/RIG_LAYOUT.md    the same as a table of coordinates in centimetres, to lay out with a tape measure
Usage: python scripts/make_rig_layout.py [scenario.json]
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from sandtable.spatial import Twin, default_registration  # noqa: E402

scenario_path = ROOT / (sys.argv[1] if len(sys.argv) > 1 else "hardware/scenarios/sandtable_rig_3A2T.json")
scenario = json.loads(scenario_path.read_text())
twin = Twin(json.loads((ROOT / "fixtures/building/twin.json").read_text()))
anchors = scenario["anchors"]
reg = default_registration(anchors, twin)
to_rig = lambda p: reg.invert(p[0], p[1])
cm = lambda v: round(v * 100)

ax = [a["x"] for a in anchors.values()]
ay = [a["y"] for a in anchors.values()]
W, H = max(ax) - min(ax), max(ay) - min(ay)
K = 200 if max(W, H) < 6 else 100                       # svg px per metre
pad = 0.35
sx = lambda x: (x - min(ax) + pad) * K
sy = lambda y: (max(ay) - y + pad) * K
parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {(W + 2 * pad) * K:.0f} {(H + 2 * pad) * K:.0f}" font-family="Arial, sans-serif">',
         f'<rect width="100%" height="100%" fill="#fff"/>',
         f'<rect x="{sx(min(ax)):.1f}" y="{sy(max(ay)):.1f}" width="{W * K:.1f}" height="{H * K:.1f}" fill="none" stroke="#bbb" stroke-dasharray="6 5"/>']
for r in twin.data["rooms"]:
    pts = " ".join(f"{sx(x):.1f},{sy(y):.1f}" for x, y in (to_rig(p) for p in r["polygon"]))
    fill = {"corridor": "#f1f1e6", "stair": "#d6ecd9", "suite": "#eef3f8"}.get(r["kind"], "#eee")
    parts.append(f'<polygon points="{pts}" fill="{fill}" stroke="#333" stroke-width="1.2"/>')
    c = to_rig(twin.room_centre(r["id"]))
    label = r["suite"] if r["kind"] == "suite" else r["label"] if r["kind"] in ("stair", "lobby") else ""
    if label:
        parts.append(f'<text x="{sx(c[0]):.1f}" y="{sy(c[1]):.1f}" font-size="{0.09 * K:.0f}" text-anchor="middle" fill="#222">{label}</text>')
for d in twin.data["doors"]:
    x, y = to_rig(d["at"])
    parts.append(f'<circle cx="{sx(x):.1f}" cy="{sy(y):.1f}" r="{0.025 * K:.1f}" fill="#d33"/>')
for aid, a in anchors.items():
    parts.append(f'<path d="M{sx(a["x"]):.1f} {sy(a["y"]) - 0.07 * K:.1f} l{0.06 * K:.1f} {0.11 * K:.1f} h{-0.12 * K:.1f} z" fill="#111"/>')
    parts.append(f'<text x="{sx(a["x"]):.1f}" y="{sy(a["y"]) + 0.16 * K:.1f}" font-size="{0.08 * K:.0f}" text-anchor="middle" font-weight="bold">{aid} ({cm(a["x"])}, {cm(a["y"])}) cm</text>')
parts.append(f'<text x="{pad * K * 0.3:.0f}" y="{0.16 * K:.0f}" font-size="{0.075 * K:.0f}" fill="#444">Sandtable rig, scale 1:{reg.scale:.1f} ({scenario["name"]}). Rig origin = anchor A1. Red dots = doors. Dashed = anchor rectangle.</text>')
parts.append("</svg>")
(ROOT / "hardware" / "rig_layout.svg").write_text("\n".join(parts))

floor = twin.floor()
rows = ["# Rig layout (exercise mode)", "",
        f"Generated by `scripts/make_rig_layout.py` from `{scenario_path.relative_to(ROOT)}` and the twin. Scale 1:{reg.scale:.1f}: "
        f"1 cm on the rig is {reg.scale:.1f} cm in the building. Coordinates are centimetres in the rig frame: origin at anchor A1, x towards A2, y away from the A1-A2 line.",
        "", "The drawing is `hardware/rig_layout.svg` (vector: print it tiled as a poster, or just use this table and painter's tape).", "",
        "## Anchors", "", "| Anchor | x cm | y cm | height |", "|---|---|---|---|"]
for aid, a in anchors.items():
    rows.append(f"| {aid} | {cm(a['x'])} | {cm(a['y'])} | {cm(a.get('z', 0))} cm above the plan |")
rows += ["", "## Floor outline corners (tape these first)", "", "| Corner | x cm | y cm |", "|---|---|---|"]
for i, p in enumerate(floor["outline"]):
    x, y = to_rig(p)
    rows.append(f"| {i + 1} | {cm(x)} | {cm(y)} |")
rows += ["", "## Rooms (tape the rectangle, write the label inside)", "", "| Room | x min | y min | x max | y max |", "|---|---|---|---|---|"]
for r in twin.data["rooms"]:
    pts = [to_rig(p) for p in r["polygon"]]
    rows.append(f"| {r['label']} | {cm(min(p[0] for p in pts))} | {cm(min(p[1] for p in pts))} | {cm(max(p[0] for p in pts))} | {cm(max(p[1] for p in pts))} |")
rows += ["", "## Doors and calibration marks", "", "| Mark | x cm | y cm |", "|---|---|---|"]
for d in twin.data["doors"]:
    x, y = to_rig(d["at"])
    rows.append(f"| {d['id']}: door of {twin.room(d['rooms'][0])['label']} | {cm(x)} | {cm(y)} |")
(ROOT / "hardware" / "RIG_LAYOUT.md").write_text("\n".join(rows) + "\n")
print(f"wrote hardware/rig_layout.svg and hardware/RIG_LAYOUT.md (scale 1:{reg.scale:.1f}, rig {W:.2f} x {H:.2f} m)")
